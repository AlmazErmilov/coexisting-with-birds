/** Return profile data, or null when a scientific name is unavailable. */
export function getBirdInfo(name) {
  if (typeof name !== "string") return null;
  const scientificName = name.trim();
  return Object.hasOwn(BIRD_INFO, scientificName) ? BIRD_INFO[scientificName] : null;
}
